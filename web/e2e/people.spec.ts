import { expect, openAs, quiet, seriousA11yViolations, settle, test } from './fixtures'

/** Yesterday's date in Asia/Jakarta (the demo sites' time zone). */
function yesterdayWib(): string {
  const d = new Date(Date.now() + 7 * 3600_000 - 86_400_000)
  return d.toISOString().slice(0, 10)
}

// People & access (F1, F4, F6, D-046, D-049) — once, at desktop width.
test.describe('people & access (demo) @desktop', () => {
  test('create a user with a temporary password shown once', async ({ page, problems }) => {
    await openAs(page, 'admin', '/users')
    await page.getByRole('button', { name: 'Tambah pengguna' }).first().click()
    const dialog = page.getByRole('dialog', { name: 'Tambah pengguna' })
    await dialog.getByLabel(/Nama pengguna/).fill('Spv.Sari')
    await dialog.getByLabel(/Nama depan/).fill('Sari')
    await dialog.getByRole('checkbox', { name: /^Supervisor/ }).check()
    await dialog.getByRole('radio', { name: /Hanya lokasi berikut/ }).check()
    await dialog.getByRole('radio', { name: /Atur kata sandi sementara sekarang/ }).check()
    await quiet(page)
    expect(await seriousA11yViolations(page)).toEqual([])
    await dialog.getByRole('button', { name: 'Buat pengguna' }).click()

    const done = page.getByRole('dialog', { name: 'Sari sudah dibuat' })
    await expect(done.getByText('Hanya ditampilkan sekali')).toBeVisible()
    const secret = done.getByRole('textbox', { name: 'Kata sandi sementara' })
    await expect(secret).toHaveValue(/^[A-Za-z0-9]{16}$/)
    await expect(done.getByRole('button', { name: /^Salin/ })).toBeVisible()
    await done.getByRole('button', { name: 'Selesai, sudah saya salin' }).click()

    await page.getByLabel('Cari pengguna').fill('spv.sari')
    const row = page.getByRole('row').filter({ hasText: 'spv.sari' })
    await expect(row).toBeVisible()
    await expect(row.getByText('Gudang Cikarang')).toBeVisible()
    await expect(row.getByText('Wajib ganti kata sandi')).toBeVisible()
    expect(problems).toEqual([])
  })

  test('API errors show next to the field (username taken)', async ({ page, problems }) => {
    await openAs(page, 'admin', '/users?new=1')
    const dialog = page.getByRole('dialog', { name: 'Tambah pengguna' })
    await dialog.getByLabel(/Nama pengguna/).fill('spv.budi')
    await dialog.getByLabel(/Alamat e-mail/).fill('budi2@example.com')
    await dialog.getByRole('checkbox', { name: /^HR/ }).check()
    await dialog.getByRole('button', { name: 'Buat pengguna' }).click()
    await expect(dialog.getByText('Nama pengguna ini sudah dipakai.')).toBeVisible()
    await expect(dialog.getByLabel(/Nama pengguna/)).toHaveAttribute('aria-invalid', 'true')
    expect(problems).toEqual([])
  })

  test('self-protection: own admin role and status are locked', async ({ page, problems }) => {
    await openAs(page, 'admin', '/users')
    await page.getByRole('button', { name: 'Kelola — Rina Kusuma' }).click()
    const drawer = page.getByRole('dialog', { name: 'Pengguna — Rina Kusuma' })
    await expect(drawer.getByText('Anda', { exact: true })).toBeVisible()
    await expect(drawer.getByRole('checkbox', { name: /^Administrator/ })).toBeDisabled()
    await expect(drawer.getByRole('switch', { name: 'Akun aktif' })).toBeDisabled()
    await expect(drawer.getByRole('button', { name: /^Reset kata sandi/ })).toBeDisabled()
    await quiet(page)
    expect(await seriousA11yViolations(page)).toEqual([])
    expect(problems).toEqual([])
  })

  test('reset a password and re-enable a disabled user', async ({ page, problems }) => {
    await openAs(page, 'admin', '/users')
    await page.getByRole('button', { name: 'Kelola — Andi Firmansyah' }).click()
    let drawer = page.getByRole('dialog', { name: 'Pengguna — Andi Firmansyah' })
    await expect(drawer.getByText('Akun ini nonaktif — pengguna tidak dapat masuk.')).toBeVisible()
    await drawer.getByRole('button', { name: 'Aktifkan akun' }).click()
    await expect(page.getByRole('status').getByText('Andi Firmansyah dapat masuk lagi.')).toBeVisible()
    await drawer.getByRole('button', { name: 'Reset kata sandi — Andi Firmansyah' }).click()
    const reset = page.getByRole('dialog', { name: 'Reset kata sandi — Andi Firmansyah' })
    await reset.getByRole('radio', { name: /Atur kata sandi sementara/ }).check()
    await reset.getByRole('button', { name: 'Reset kata sandi' }).click()
    drawer = page.getByRole('dialog', { name: 'Kata sandi sementara baru — Andi Firmansyah' })
    await expect(drawer.getByRole('textbox', { name: 'Kata sandi sementara' })).toHaveValue(/^[A-Za-z0-9]{16}$/)
    expect(problems).toEqual([])
  })

  test('tablet account: password shown once with sign-in details', async ({ page, problems }) => {
    await openAs(page, 'admin', '/settings?tab=devices')
    await page.getByRole('button', { name: 'Akun tablet baru' }).first().click()
    const dialog = page.getByRole('dialog', { name: 'Akun tablet baru' })
    await dialog.getByLabel(/Nama tablet/).fill('Pos Gerbang Timur')
    await expect(dialog.getByText('Nama pengguna: device-pos-gerbang-timur')).toBeVisible()
    await dialog.getByRole('button', { name: 'Buat akun' }).click()
    const done = page.getByRole('dialog', { name: 'Akun tablet untuk Pos Gerbang Timur' })
    await expect(done.getByRole('textbox', { name: 'Kata sandi tablet' })).toHaveValue(/^[A-Za-z0-9]{24}$/)
    await expect(done.getByText('Cara masuk di tablet')).toBeVisible()
    await expect(done.getByText('demo', { exact: true })).toBeVisible()
    await expect(done.getByText('device-pos-gerbang-timur', { exact: true })).toBeVisible()
    await quiet(page)
    expect(await seriousA11yViolations(page)).toEqual([])
    await done.getByRole('button', { name: 'Selesai, sudah saya salin' }).click()
    await expect(page.getByText('device-pos-gerbang-timur')).toBeVisible()
    expect(problems).toEqual([])
  })

  test('tablet health: warning badge opens the details', async ({ page, problems }) => {
    await openAs(page, 'admin', '/settings?tab=devices')
    await page.getByRole('button', { name: /Kesehatan tablet: 3 peringatan — Tablet Lobby Sudirman/ }).click()
    const drawer = page.getByRole('dialog', { name: 'Kesehatan tablet — Tablet Lobby Sudirman' })
    await expect(drawer.getByText('Jam tablet selisih lebih dari 2 menit')).toBeVisible()
    await expect(drawer.getByText('+3 mnt 12 dtk')).toBeVisible()
    await expect(drawer.getByText(/SocketException/)).toBeVisible()
    await quiet(page)
    expect(await seriousA11yViolations(page)).toEqual([])
    await drawer.getByRole('button', { name: 'Tutup' }).first().click()
    await expect(page.getByRole('button', { name: /Kesehatan tablet: Sehat — Tablet Pos Utama Cikarang/ })).toBeVisible()
    expect(problems).toEqual([])
  })

  test('attendance correction history (site time zone)', async ({ page, problems }) => {
    await openAs(page, 'hr', `/attendance?date=${yesterdayWib()}`)
    await page.getByRole('button', { name: /^Riwayat — / }).first().click()
    const drawer = page.getByRole('dialog', { name: /^Riwayat koreksi — / })
    await expect(drawer.getByText('2 koreksi, terlama lebih dulu. Waktu menurut zona waktu lokasi.')).toBeVisible()
    await expect(drawer.getByText(/mengantar korban kecelakaan/).first()).toBeVisible()
    await expect(drawer.getByText(/tablet mati/).first()).toBeVisible()
    await expect(drawer.getByText('admin.rina').first()).toBeVisible()
    await quiet(page)
    expect(await seriousA11yViolations(page)).toEqual([])
    expect(problems).toEqual([])
  })

  test('visitor detail reveals the full ID number only on request', async ({ page, problems }) => {
    await openAs(page, 'supervisor', '/incidents?tab=visitors')
    await page.getByRole('button', { name: 'Detail — Hasan Basri' }).click()
    const drawer = page.getByRole('dialog', { name: 'Tamu — Hasan Basri' })
    await expect(drawer.getByText('Disamarkan')).toBeVisible()
    await expect(drawer.getByText(/\*{4,}/)).toBeVisible()
    await drawer.getByRole('button', { name: 'Tampilkan nomor identitas dan foto' }).click()
    await expect(drawer.getByText('Nomor lengkap ditampilkan')).toBeVisible()
    await expect(drawer.getByText(/^32\d+$/)).toBeVisible()
    await expect(drawer.getByRole('img', { name: 'Foto tamu Hasan Basri' })).toBeVisible()
    expect(problems).toEqual([])
  })

  test('site-scoped client sees its limit in the user menu', async ({ page, problems }) => {
    await openAs(page, 'client-readonly', '/')
    await page.getByRole('button', { name: 'Menu pengguna' }).click()
    await expect(page.getByText('Dibatasi ke 1 lokasi')).toBeVisible()
    await settle(page)
    expect(problems).toEqual([])
  })
})
